#!/bin/bash
# 开启严格模式：任何一行命令失败，或者引用未定义变量，立即停止脚本
set -euo pipefail

echo "======================================================="
echo "🔍 阶段 1: 注入运行时环境并执行配置洗涤..."
echo "======================================================="

# 1. 优先执行 setup.sh
# 注意：如果你的 setup.sh 正常执行完毕，它必须返回 exit 0（成功）
if ! bash setup.sh; then
    echo "❌ [构建拦截] setup.sh 脚本执行过程中抛出异常或中断！"
    exit 1
fi

# 2. 🛡️ 终极物理二次校验（防止 setup.sh 虽然跑完，但其实没有替换到任何文件的假成功）
# 我们通过全盘嗅探 src/main/java 中是否还残留硬编码的特征字符串 "ECDSA_B64..." 
if grep -r "ECDSA_B64\.\.\." src/main/java/ > /dev/null 2>&1; then
    echo "❌ [构建拦截] 二次指纹校验失败！源码中依然检测到硬编码占位符 'ECDSA_B64...'，替换未真正生效！"
    echo "💡 请检查：1. 环境变量是否正确传入； 2. 主类中是否存在 'this.agent = new kisama(' 特征代码。"
    exit 1
fi
echo "======================================================="
echo "🚀 阶段 2: 初始化 Gradle Wrapper..."
echo "======================================================="
gradle wrapper --gradle-version 8.14.2 --distribution-type=bin --no-daemon --configure-on-demand
echo "======================================================="
echo "✅ 阶段 3: 替换指纹校验通过！开始编译多态副本..."
echo "======================================================="
./gradlew build